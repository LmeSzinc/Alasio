"""
Tests for the lock file a compile writes (alasio/deploy_dev/compile/writer.py).
"""
import pytest

from alasio.deploy.simple_pip.parse_req import Requirements
from alasio.deploy_dev.compile import Index, Resolution, requirements_text
from alasio.testing.filesystem import fs  # noqa: F401

pytestmark = [
    pytest.mark.parallel,
]

PRIMARY = Index.of('https://pypi.org/simple', primary=True)
BACKPORT = Index.of('https://backport.example/simple/')


def resolution_of(pins, sources=None, parents=None):
    """
    A resolution of the given pins.

    Args:
        pins (dict[str, str]): {name: version}
        sources (dict[str, str] | None): {name: index url}
        parents (dict[str, tuple[str, ...]] | None): {name: origins}

    Returns:
        Resolution: The resolution
    """
    return Resolution(
        pins=dict(pins),
        sources=dict(sources or {}),
        parents={name: tuple(value) for name, value in (parents or {}).items()},
    )


class TestRequirementsText:
    """The format of the lock file, the one the client parser reads."""

    def test_a_single_pin(self):
        text = requirements_text('demo', resolution_of(
            {'httpx2': '2.16.0'}, {'httpx2': PRIMARY.url}, {'httpx2': ('pyproject.toml',)}))

        assert text == """\
httpx2==2.16.0
    # via demo (pyproject.toml)
    # from https://pypi.org/simple
"""

    def test_the_pins_are_sorted(self):
        text = requirements_text('demo', resolution_of({'zope': '1.0', 'attrs': '2.0'}))

        assert [line for line in text.splitlines() if '==' in line] == [
            'attrs==2.0', 'zope==1.0']

    def test_several_parents(self):
        text = requirements_text('demo', resolution_of(
            {'shared': '1.0'},
            parents={'shared': ('demo', 'other')}))

        assert text == """\
shared==1.0
    # via
    #   demo
    #   other
"""

    def test_the_parents_are_sorted(self):
        text = requirements_text('demo', resolution_of(
            {'shared': '1.0'},
            parents={'shared': ('other', 'pyproject.toml')}))

        assert text == """\
shared==1.0
    # via
    #   demo (pyproject.toml)
    #   other
"""

    def test_an_extra_index_is_declared(self):
        text = requirements_text('demo', resolution_of(
            {'pyjwt': '2.15.1'}, {'pyjwt': BACKPORT.url}),
            [PRIMARY, BACKPORT])

        assert text == """\
--extra-index-url https://backport.example/simple/

pyjwt==2.15.1
    # from https://backport.example/simple/
"""

    def test_an_unused_extra_index_is_not_declared(self):
        text = requirements_text('demo', resolution_of(
            {'pyjwt': '2.15.1'}, {'pyjwt': PRIMARY.url}),
            [PRIMARY, BACKPORT])

        assert '--extra-index-url' not in text

    def test_the_header(self):
        text = requirements_text(
            'demo', resolution_of({'demo': '1.0'}), header='# generated by a tool\n# do not edit')

        assert text == """\
# generated by a tool
# do not edit

demo==1.0
"""

    def test_a_pin_without_a_source_or_a_parent(self):
        text = requirements_text('demo', resolution_of({'demo': '1.0'}))

        assert text == 'demo==1.0\n'

    def test_the_client_parser_reads_it_back(self):
        text = requirements_text(
            'demo',
            resolution_of(
                {'httpx2': '2.16.0', 'pyjwt': '2.15.1'},
                {'httpx2': PRIMARY.url, 'pyjwt': BACKPORT.url},
                {'httpx2': ('pyproject.toml',), 'pyjwt': ('httpx2',)},
            ),
            [PRIMARY, BACKPORT],
        )

        pins = Requirements(text).dict_deps

        assert pins == {'httpx2': '2.16.0', 'pyjwt': '2.15.1'}
