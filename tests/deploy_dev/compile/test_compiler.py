"""
Tests for the compiler of a project (alasio/deploy_dev/compile/compiler.py).

The project is a pyproject.toml of the fake filesystem, the indexes are the
mock network of tests/deploy_dev/compile/conftest.py: a compile reads the
declaration, resolves the versions, writes the lock and reads it back.
"""
import pytest

from alasio.deploy.pip_download._target_python import TargetPython
from alasio.deploy_dev.compile import CompileError, RequirementsCompile
from alasio.ext.path.atomic import atomic_read_text
from alasio.logger import logger
from alasio.testing.filesystem import fs  # noqa: F401
from tests.deploy_dev.compile.conftest import INDEX_URL, MOCK_INDEX_URL, write_pyproject

pytestmark = [
    pytest.mark.parallel,
]

# A linux python 3.8 target, whatever runs the suite
TARGET = TargetPython(py_version_info=(3, 8, 20), platforms=['manylinux2014_x86_64'])

HEADER = '# generated by a tool\n# do not edit'


def pyproject(*dependencies, name='demo_project', tables=''):
    """
    A pyproject.toml content of the tests.

    Args:
        *dependencies (str): PEP 508 requirements of [project].dependencies
        name (str): Name of the project. Defaults to PROJECT_NAME
        tables (str): Extra TOML written after the [project] table

    Returns:
        str: Content of the file
    """
    listed = ''.join(f'    "{dep}",\n' for dep in dependencies)
    return f'[project]\nname = "{name}"\nversion = "1.0.0"\ndependencies = [\n{listed}]\n\n{tables}'


def compiler_of(project, network, **kwargs):
    """
    A compiler over the mock network.

    Args:
        project (PathStr): Root of the project
        network (MockNetwork): The mock network
        **kwargs: Options of the compiler

    Returns:
        RequirementsCompile: The compiler
    """
    kwargs.setdefault('target', TARGET)
    kwargs.setdefault('header', HEADER)
    return RequirementsCompile(root=project, client=network.client, **kwargs)


class TestCompile:
    """The pins of a project, and the file it writes."""

    @pytest.mark.trio
    async def test_a_project_of_one_dependency(self, project, network):
        write_pyproject(project, pyproject('demo>=1'))
        network.index().add('demo', '1.5', requires=['leaf'])
        network.index().add('leaf', '2.0')

        result = await compiler_of(project, network).compile_async()

        assert result.pins == {'demo': '1.5', 'leaf': '2.0'}
        assert result.written is True
        assert atomic_read_text(project.joinpath('requirements.txt')) == f"""\
{HEADER}

demo==1.5
    # via demo-project (pyproject.toml)
    # from {INDEX_URL}
leaf==2.0
    # via demo
    # from {INDEX_URL}
"""

    @pytest.mark.trio
    async def test_the_version_range_of_the_declaration(self, project, network):
        write_pyproject(project, pyproject('numpy<2'))
        network.index().add('numpy', '1.24.4')
        network.index().add('numpy', '2.1.0')

        result = await compiler_of(project, network).compile_async()

        assert result.pins == {'numpy': '1.24.4'}

    @pytest.mark.trio
    async def test_a_second_run_writes_nothing(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        compiler = compiler_of(project, network)

        assert (await compiler.compile_async()).written is True
        assert (await compiler.compile_async()).written is False

    @pytest.mark.trio
    async def test_the_previous_pin_is_preferred(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        await compiler_of(project, network).compile_async()
        # a new version is published, the lock keeps what it has
        network.index().add('demo', '1.1')

        result = await compiler_of(project, network).compile_async()

        assert result.pins == {'demo': '1.0'}
        assert result.written is False

    @pytest.mark.trio
    async def test_upgrade_moves_the_pin(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        await compiler_of(project, network).compile_async()
        network.index().add('demo', '1.2')

        result = await compiler_of(project, network).compile_async(upgrade=True)

        assert result.pins == {'demo': '1.2'}
        assert result.changed == ['demo']
        assert result.written is True

    @pytest.mark.trio
    async def test_a_dependency_that_is_dropped(self, project, network):
        write_pyproject(project, pyproject('demo', 'dropped'))
        network.index().add('demo', '1.0')
        network.index().add('dropped', '1.0')
        await compiler_of(project, network).compile_async()

        write_pyproject(project, pyproject('demo'))
        result = await compiler_of(project, network).compile_async()

        assert result.removed == ['dropped']
        assert 'dropped' not in result.pins

    @pytest.mark.trio
    async def test_a_given_provider_is_reused(self, project, network):
        """A compile over a provider that already read the pages costs no request."""
        from alasio.deploy_dev.metadata import MetadataProvider

        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        provider = MetadataProvider(client=network.client)
        await compiler_of(project, network, provider=provider).compile_async()
        before = list(network.requests)

        result = await compiler_of(
            project, network, provider=provider).compile_async(upgrade=True)

        assert result.pins == {'demo': '1.0'}
        assert network.requests == before
        await provider.aclose()

    @pytest.mark.trio
    async def test_the_output_path(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')

        result = await compiler_of(
            project, network, output='deploy/requirements.txt').compile_async()

        assert result.path.replace('\\', '/').endswith('deploy/requirements.txt')
        assert 'demo==1.0' in atomic_read_text(project.joinpath('deploy/requirements.txt'))


class TestTheRun:
    """One instance, both tools: the compile and the pack channel of the mod."""

    @staticmethod
    def write_entry(root, index=INDEX_URL):
        """
        Declare the mod entry ``pack_deps`` maintains.

        Args:
            root (PathStr): Root of the project
            index (str): Value of ``Update.pypi_mirrors``. Defaults to INDEX_URL

        Returns:
            PathStr: Path of the declaration
        """
        file = root.joinpath('module/config/_index/mod_entry.yaml')
        file.atomic_write(
            f'Mod:\n  name: demo_mod\n'
            f'Update:\n  pypi_mirrors: {index}\n  pack_deps: []\n'.encode('utf-8'))
        return file

    @pytest.mark.trio
    async def test_the_second_compile_costs_no_request(self, project, network):
        """The reader of the instance outlives the call, so a rerun is cached."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        job = compiler_of(project, network)
        await job.compile_async()
        before = list(network.requests)

        result = await job.compile_async(upgrade=True)

        assert result.pins == {'demo': '1.0'}
        assert network.requests == before
        await job.aclose_async()

    @pytest.mark.trio
    async def test_the_pack_deps_is_one_manager_of_the_run(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        self.write_entry(project)
        job = compiler_of(project, network)

        assert job.pack_deps is job.pack_deps
        await job.aclose_async()

    @pytest.mark.trio
    async def test_the_pack_deps_shares_the_metadata_of_the_compile(self, project, network):
        """The decisions of the same run read no page and no METADATA again."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0', requires=['leaf'])
        network.index().add('leaf', '2.0')
        self.write_entry(project)
        job = compiler_of(project, network)
        await job.compile_async()
        before = list(network.requests)

        manager = job.pack_deps
        manager.register('demo', recursive=True)
        decisions = await manager.resolve_async()

        assert set(decisions) == {'demo', 'leaf'}
        assert network.requests == before
        await job.aclose_async()

    @pytest.mark.trio
    async def test_the_pack_deps_reads_the_lock_the_compile_wrote(self, project, network):
        """The manager of the run decides the pins of the file just written."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.4')
        self.write_entry(project)
        job = compiler_of(project, network)
        result = await job.compile_async()

        manager = job.pack_deps
        manager.register('demo')
        decisions = await manager.resolve_async()

        assert decisions['demo'].version == result.pins['demo']
        await job.aclose_async()

    def test_aclose_drops_the_reader_of_the_run(self, project, network):
        """The reader lives with the instance, and aclosed() ends it."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        job = compiler_of(project, network)
        job.compile()
        assert 'provider' in job.__dict__

        job.aclose()

        assert 'provider' not in job.__dict__
        # closing twice is not an error, like the client of the domain
        job.aclose()

    def test_the_block_closes_the_run(self, project, network):
        """A caller writes the with block and calls no close."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        job = compiler_of(project, network)

        with job as entered:
            assert entered is job
            result = job.compile()
            assert 'provider' in job.__dict__

        assert result.pins == {'demo': '1.0'}
        assert 'provider' not in job.__dict__

    def test_the_block_closes_the_run_of_a_failure(self, project, network):
        """An exception of the block still closes the reader."""
        write_pyproject(project, pyproject('demo>=2'))
        network.index().add('demo', '1.0')
        job = compiler_of(project, network)

        with pytest.raises(CompileError):
            with job:
                job.compile()

        assert 'provider' not in job.__dict__

    @pytest.mark.trio
    async def test_the_async_block_closes_the_run(self, project, network):
        """An async caller uses async with, and it closes the same things."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        job = compiler_of(project, network)

        async with job as entered:
            assert entered is job
            result = await job.compile_async()
            assert 'provider' in job.__dict__

        assert result.pins == {'demo': '1.0'}
        assert 'provider' not in job.__dict__

    def test_aclose_keeps_a_given_reader(self, project, network):
        """A reader given to the constructor belongs to the caller."""
        from alasio.deploy_dev.metadata import MetadataProvider

        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        provider = MetadataProvider(client=network.client)
        job = compiler_of(project, network, provider=provider)
        job.compile()

        job.aclose()

        assert 'provider' in job.__dict__


class TestDeclaration:
    """What the compiler reads from the pyproject.toml."""

    @pytest.mark.trio
    async def test_an_extra(self, project, network):
        write_pyproject(project, pyproject(
            'demo',
            tables='\n[project.optional-dependencies]\nimage = ["opencv"]\n',
        ))
        network.index().add('demo', '1.0')
        network.index().add('opencv', '4.0')

        result = await compiler_of(project, network).compile_async(extras=['image'])

        assert set(result.pins) == {'demo', 'opencv'}

    @pytest.mark.trio
    async def test_every_extra(self, project, network):
        write_pyproject(project, pyproject(
            'demo',
            tables=(
                '\n[project.optional-dependencies]\n'
                'image = ["opencv"]\ndev = ["pytest"]\n'
            ),
        ))
        network.index().add('demo', '1.0')
        network.index().add('opencv', '4.0')
        network.index().add('pytest', '8.0')

        result = await compiler_of(project, network).compile_async(all_extras=True)

        assert set(result.pins) == {'demo', 'opencv', 'pytest'}

    @pytest.mark.trio
    async def test_a_dependency_group(self, project, network):
        write_pyproject(project, pyproject(
            'demo',
            tables='\n[dependency-groups]\nlint = ["ruff>=0.16"]\n',
        ))
        network.index().add('demo', '1.0')
        network.index().add('ruff', '0.16.1')

        result = await compiler_of(project, network).compile_async(groups=['lint'])

        assert set(result.pins) == {'demo', 'ruff'}

    @pytest.mark.trio
    async def test_an_extra_index(self, project, network):
        write_pyproject(project, pyproject('pyjwt', tables=(
            '\n[[tool.uv.index]]\n'
            'name = "backport"\n'
            f'url = "{MOCK_INDEX_URL}/"\n'
        )))
        network.index(MOCK_INDEX_URL).add('pyjwt', '2.15.1')

        result = await compiler_of(project, network).compile_async()

        assert result.sources == {'pyjwt': MOCK_INDEX_URL}
        text = atomic_read_text(project.joinpath('requirements.txt'))
        assert f'--extra-index-url {MOCK_INDEX_URL}/' in text
        assert f'# from {MOCK_INDEX_URL}/' in text

    @pytest.mark.trio
    async def test_an_index_that_replaces_pypi(self, project, network):
        write_pyproject(project, pyproject('demo', tables=(
            '\n[[tool.uv.index]]\n'
            'name = "backport"\n'
            f'url = "{MOCK_INDEX_URL}/"\n'
            'default = true\n'
        )))
        network.index(MOCK_INDEX_URL).add('demo', '1.0')

        result = await compiler_of(project, network).compile_async()

        assert result.pins == {'demo': '1.0'}
        # the primary index is not declared as an extra one
        text = atomic_read_text(project.joinpath('requirements.txt'))
        assert '--extra-index-url' not in text

    @pytest.mark.trio
    async def test_a_named_source(self, project, network):
        write_pyproject(project, pyproject('demo', 'private', tables=(
            '\n[[tool.uv.index]]\n'
            'name = "backport"\n'
            f'url = "{MOCK_INDEX_URL}/"\n'
            '\n[tool.uv.sources]\n'
            'private = { index = "backport" }\n'
        )))
        network.index().add('demo', '1.0')
        network.index(MOCK_INDEX_URL).add('private', '0.9')

        result = await compiler_of(project, network).compile_async()

        assert result.sources['private'] == MOCK_INDEX_URL

    @pytest.mark.trio
    async def test_a_source_the_compiler_does_not_read(self, project, network):
        write_pyproject(project, pyproject('demo', tables=(
            '\n[tool.uv.sources]\ndemo = { git = "https://example.com/demo.git" }\n'
        )))

        with pytest.raises(CompileError, match='does not read'):
            await compiler_of(project, network).compile_async()

    @pytest.mark.trio
    async def test_a_source_that_names_an_unknown_index(self, project, network):
        write_pyproject(project, pyproject('demo', tables=(
            '\n[tool.uv.sources]\ndemo = { index = "nowhere" }\n'
        )))

        with pytest.raises(CompileError, match='does not declare in'):
            await compiler_of(project, network).compile_async()


class TestErrors:
    """What the compiler refuses."""

    @pytest.mark.trio
    async def test_a_project_without_a_pyproject(self, project, network, fs):
        fs.remove(project.joinpath('pyproject.toml'))

        with pytest.raises(CompileError, match='no dependency file'):
            await compiler_of(project, network).compile_async()

    @pytest.mark.trio
    async def test_a_project_without_dependencies(self, project, network):
        write_pyproject(project, pyproject())

        with pytest.raises(CompileError, match='nothing to compile'):
            await compiler_of(project, network).compile_async()

    @pytest.mark.trio
    async def test_a_project_without_a_name(self, project, network):
        write_pyproject(project, '[project]\ndependencies = ["demo"]\n')

        with pytest.raises(CompileError, match='declares no project name'):
            await compiler_of(project, network).compile_async()

    @pytest.mark.trio
    async def test_a_constraint_no_version_satisfies(self, project, network):
        write_pyproject(project, pyproject('demo>=5'))
        network.index().add('demo', '1.0')

        with pytest.raises(CompileError, match='No version of "demo"'):
            await compiler_of(project, network).compile_async()
        # nothing is written on a failure
        assert not project.joinpath('requirements.txt').exists()

    @pytest.mark.trio
    async def test_a_lock_that_is_not_a_requirements_file(self, project, network):
        """An existing file the parser cannot read as a pin is no pins at all."""
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')
        project.joinpath('requirements.txt').atomic_write(b'not a requirement\n')

        result = await compiler_of(project, network).compile_async()

        assert result.pins == {'demo': '1.0'}
        assert result.written is True


class TestReport:
    """What a compile logs."""

    @pytest.mark.trio
    async def test_the_summary(self, project, network):
        write_pyproject(project, pyproject('demo'))
        network.index().add('demo', '1.0')

        with logger.mock_capture_writer() as capture:
            await compiler_of(project, network).compile_async()

        assert capture.fd.any_contains('Compiled 1 pin(s): 1 added, 0 changed, 0 removed')
        assert capture.fd.any_contains('Added: demo')
