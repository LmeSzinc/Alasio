"""
Tests for the leaves of a page: a text node, a raw fragment and a comment.
"""
import pytest

from alasio.codegen.html import Comment, HtmlError, HtmlGen, Raw, Text


class TestText:
    def test_render(self):
        gen = HtmlGen()
        gen.P(Text(gen, 'a < b'))
        assert gen.generate_str() == """\
<p>a &lt; b</p>
"""

    def test_number(self):
        gen = HtmlGen()
        gen.Span(Text(gen, 7))
        assert gen.generate_str() == """\
<span>7</span>
"""

    def test_empty(self):
        gen = HtmlGen()
        gen.P(Text(gen, ''))
        assert gen.generate_str() == """\
<p></p>
"""

    def test_multiline(self):
        """A text of several lines is one line of the page per line."""
        gen = HtmlGen()
        with gen.Pre():
            gen.Text('a\nb')
        assert gen.generate_str() == """\
<pre>
  a
  b
</pre>
"""

    def test_multiline_escaped(self):
        gen = HtmlGen()
        with gen.Pre():
            gen.Text('<a>\n<b>')
        assert gen.generate_str() == """\
<pre>
  &lt;a&gt;
  &lt;b&gt;
</pre>
"""

    def test_value_kept(self):
        gen = HtmlGen()
        item = gen.Text('a & b')
        assert item.text == 'a & b'
        assert item.lines == ['a & b']

    def test_repr(self):
        gen = HtmlGen()
        assert repr(gen.Text('a')) == "<Text 'a'>"


class TestRaw:
    def test_not_escaped(self):
        gen = HtmlGen()
        gen.P(Raw(gen, '<b>x</b>'))
        assert gen.generate_str() == """\
<p><b>x</b></p>
"""

    def test_common_indent_stripped(self):
        """indent=True drops the indentation of the module and adds the level back."""
        gen = HtmlGen()
        with gen.Style():
            gen.Raw("""
                :root { --fg: #000; }
                body { margin: 0; }
            """)
        assert gen.generate_str() == """\
<style>
  :root { --fg: #000; }
  body { margin: 0; }
</style>
"""

    def test_indent_kept(self):
        """indent=False emits the lines as they are, indentation included."""
        gen = HtmlGen()
        with gen.Div():
            gen.Raw('a\n  b', indent=False)
        assert gen.generate_str() == """\
<div>
a
  b
</div>
"""

    def test_single_line_inline(self):
        gen = HtmlGen()
        gen.Div(Raw(gen, '<b>x</b>'))
        assert gen.generate_str() == """\
<div><b>x</b></div>
"""

    def test_single_line_without_indent_inline(self):
        gen = HtmlGen()
        gen.Div(Raw(gen, 'x', indent=False))
        assert gen.generate_str() == """\
<div>x</div>
"""

    def test_multiline_breaks_inline_parent(self):
        gen = HtmlGen()
        gen.Div(Raw(gen, 'a\nb'))
        assert gen.generate_str() == """\
<div>
  a
  b
</div>
"""

    def test_empty(self):
        gen = HtmlGen()
        gen.Div(Raw(gen, ''))
        assert gen.generate_str() == """\
<div></div>
"""

    def test_not_a_text(self):
        gen = HtmlGen()
        with pytest.raises(TypeError, match='is not a text'):
            Raw(gen, b'x')

    def test_repr(self):
        gen = HtmlGen()
        assert repr(Raw(gen, 'a\nb')) == '<Raw 2 line(s)>'


class TestComment:
    def test_render(self):
        gen = HtmlGen()
        gen.Comment('generated by alasio')
        assert gen.generate_str() == """\
<!-- generated by alasio -->
"""

    def test_inside_container(self):
        gen = HtmlGen()
        with gen.Div():
            gen.Comment('note')
            gen.P('x')
        assert gen.generate_str() == """\
<div>
  <!-- note -->
  <p>x</p>
</div>
"""

    def test_inline(self):
        gen = HtmlGen()
        gen.Div(Comment(gen, 'note'))
        assert gen.generate_str() == """\
<div><!-- note --></div>
"""

    @pytest.mark.parametrize('text', ['a -- b', 'a-', 'a\nb'])
    def test_invalid(self, text):
        gen = HtmlGen()
        with pytest.raises(ValueError, match='comment'):
            Comment(gen, text)

    def test_not_a_text(self):
        gen = HtmlGen()
        with pytest.raises(TypeError, match='is not a text'):
            Comment(gen, 1)

    def test_repr(self):
        gen = HtmlGen()
        assert repr(Comment(gen, 'a')) == "<Comment 'a'>"


class TestHtmlError:
    def test_fragment_child(self):
        """bytes cannot be a child, the message says what to do."""
        gen = HtmlGen()
        with pytest.raises(HtmlError, match='decode it to a text first'):
            gen.P(b'x')
