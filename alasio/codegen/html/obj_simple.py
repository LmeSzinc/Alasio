"""
The leaf objects of a page: a text node, a raw fragment and a comment.

The three of them are the ways a value reaches a page:

- Text: a value that is escaped, so a filename with '&' or a message with '<'
  is shown as written;
- Raw: a fragment that is already markup, emitted as it is. It is the one way
  to put markup into an element, and the caller owns the escaping of it;
- Comment: a comment, for the notes a generated file carries.

Usage:
    from alasio.codegen.html import HtmlGen, Raw

    gen = HtmlGen()
    gen.P('a < b')
    gen.P(Raw(gen, '<b>bold</b>'))
    gen.Comment('generated by alasio')
    gen.generate_str()
    # <p>a &lt; b</p>
    # <p><b>bold</b></p>
    # <!-- generated by alasio -->
"""

import inspect

from .obj_base import HtmlError, HtmlObject, NotInline, escape

__all__ = [
    'Comment',
    'Raw',
    'Text',
]


class Text(HtmlObject):
    """
    A text node.

    Args:
        gen (HtmlGenBase): Generator of the page
        text (str | int | float): Value to show, rendered with str() and escaped
    """

    def __init__(self, gen, text):
        super().__init__(gen)
        self.text = text if isinstance(text, str) else str(text)

    @property
    def lines(self):
        """
        The lines of the text.

        Returns:
            list[str]: One entry per line of the value
        """
        return self.text.split('\n')

    def generate(self):
        for line in self.lines:
            yield f'{self.indent_str}{escape(line)}'

    def inline_str(self):
        if '\n' in self.text:
            raise NotInline('A text of several lines is not rendered on one line')
        return escape(self.text)

    def __repr__(self):
        return f'<Text {self.text!r}>'


class Raw(HtmlObject):
    """
    An already escaped fragment of html, emitted as it is.

    Args:
        gen (HtmlGenBase): Generator of the page
        text (str): The fragment
        indent (bool): True to strip the common indentation of the fragment and
            add the indentation of the level it lands at (an inline style sheet
            written in the source of a module). False to emit the lines as they
            are, for a fragment whose own indentation is already the page one

    Raises:
        TypeError: If the fragment is not a text
    """

    def __init__(self, gen, text, indent=True):
        super().__init__(gen)
        if not isinstance(text, str):
            raise TypeError(f'An html fragment is not a text: {type(text).__name__}')
        if indent:
            # cleandoc() drops the blank lines at both ends and the common
            # indentation, the level of the page adds its own back
            text = inspect.cleandoc(text)
        else:
            text = text.lstrip('\n').rstrip()
        self.text = text
        self.lines = text.split('\n') if text else ['']
        self.add_indent = indent

    def generate(self):
        if self.add_indent:
            for line in self.lines:
                yield f'{self.indent_str}{line}'
        else:
            yield from self.lines

    def inline_str(self):
        if len(self.lines) != 1:
            raise NotInline('A fragment of several lines is not rendered on one line')
        return self.lines[0]

    def __repr__(self):
        return f'<Raw {len(self.lines)} line(s)>'


class Comment(HtmlObject):
    """
    A comment.

    Args:
        gen (HtmlGenBase): Generator of the page
        text (str): Text of the comment, shown as written

    Raises:
        TypeError: If the text is not a text
        ValueError: If the text cannot be a comment: a comment of HTML holds no
            '--', does not end with '-' and stays on one line. A text that does
            not fit is markup, use Raw
    """

    def __init__(self, gen, text):
        super().__init__(gen)
        if not isinstance(text, str):
            raise TypeError(f'A comment is not a text: {type(text).__name__}')
        if '--' in text:
            raise ValueError(f'A comment holds no "--": {text!r}')
        if text.endswith('-'):
            raise ValueError(f'A comment does not end with "-": {text!r}')
        if '\n' in text:
            raise ValueError(f'A comment stays on one line: {text!r}')
        self.text = text

    def inline_str(self):
        return f'<!-- {self.text} -->'

    def generate(self):
        yield f'{self.indent_str}{self.inline_str()}'

    def __repr__(self):
        return f'<Comment {self.text!r}>'


def as_text(gen, value):
    """
    Turn a child value that is not an object into a text node.

    Args:
        gen (HtmlGenBase): Generator of the page
        value (str | int | float): Value of the child

    Returns:
        Text: The value as a text node

    Raises:
        TypeError: If the value is not a text or a number
        HtmlError: If the value is a bytes, a mistake worth its own message
    """
    if isinstance(value, bytes):
        raise HtmlError(
            'A child of an html element is bytes: decode it to a text first, '
            'html has no byte string')
    if isinstance(value, (str, int, float)):
        return Text(gen, value)
    raise TypeError(
        f'A child of an html element is not an html object, a text or a number: '
        f'{type(value).__name__}')
