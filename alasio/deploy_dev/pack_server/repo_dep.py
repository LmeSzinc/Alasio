"""
Generate the packs of the python dependencies of a repo (steps 4.1 and 6).

A repo of the pack server serves the dependencies its latest commit declares in
update_pack_deps as packs, the same job machine as the repo tree: a client
downloads a pack of a version once and updates with the update packs afterwards
instead of installing the distribution with pip. Every dependency gets a
channel of its own:

    {workspace}/packdep/{name}/{new}/full.pack
    {workspace}/packdep/{name}/{new}/update_{old}.pack

Only the target version has a full pack, the rule the git flow keeps for the
latest commit: a client downloads the full pack of the version it updates to
once and updates with update packs afterwards, so a version of the window only
needs an update path to the target.

The input of the build is the pure python wheel of every version of the window:
this step fetches them to the private cache first (`_wheel_cache/{name}/{version}/`,
the index page of the version and its wheels, see fetch_wheel) and builds the
packs from there. The cache folder is shared with repo_wheel, which fetches the
wheels of the pins the repo provides: a version both steps fetch is downloaded
by the first of them and answered by the local files of the second.

The bytes of a pack only depend on the wheel of its version, so the pack of an
earlier run is kept as it is: the identity of the file is read back (kept_pack)
and a file of another format, of another version pair, or a file that cannot be
read as a pack is written again. A run over a channel that is up to date builds
nothing; its wheels are read from the cache, the network is not asked.

The run leaves the snapshots of the channels it generated on the instance (the
`published` attribute): the version and the index checksum of every dependency
whose latest commit pin has a target. The repo tree pack carries them (see
repo_pack): the client reads the version of every channel from there, never
from a per dependency latest.pack.

Usage:
    from alasio.deploy_dev.pack_server.repo_base import RepoBase
    from alasio.deploy_dev.pack_server.repo_dep import RepoDep

    base = RepoBase(repo, config.data)
    dep = RepoDep(base)
    dep.run()
    dep.published
"""

import trio

from alasio.deploy.pack.packdep import validate_packdep_name
from alasio.deploy.pip_download.pypi_file import DOWNLOAD_MODE_PY3_ANY
from alasio.deploy_dev.pack.pack_wheel import PackWheel
from alasio.deploy_dev.pack.pack_wheel_update import PackWheelUpdate
from alasio.deploy_dev.pack_server.fetch_wheel import WheelFetcher, WheelNotFoundError
from alasio.deploy_dev.pack_server.pack_check import PackChecksum, kept_pack
from alasio.deploy_dev.pack_server.repo_base import DEFAULT_INDEX
from alasio.ext.path.atomic import atomic_write_stream
from alasio.ext.path.validate import validate_filename
from alasio.logger import logger

# file of the full pack of a version, in the folder of the version
FULL_PACK_FILE = 'full.pack'


class RepoDep:
    """
    Generate the packs of the dependencies of a repo, see the module docstring.

    Usage:
        dep = RepoDep(base)
        dep.run()
    """

    def __init__(self, base):
        """
        Args:
            base (RepoBase): Workspace and declarations of the repo
        """
        self.base = base
        # {name: (version, index checksum)} of the channels generated by
        # run(), filled while the target full packs are written/kept. It is
        # read from the full packs, never from a per dependency latest.pack.
        self.published = {}

    def run(self):
        """
        Fetch the wheels of the window, then write the packs of every dependency.

        The wheels are fetched first: a version without a usable wheel fails
        the run before anything is written, so no channel is left with a pack
        of another version. A run with no sampled dependency fetches nothing.
        Nothing is deleted here: the previous channel keeps serving the clients
        until commit() is called after the repo tree is published.

        Raises:
            ValueError: If a wheel is not a pack target, see PackWheel
            WheelNotFoundError: If a version has no usable wheel
            httpx2.HTTPError: If a wheel cannot be fetched
            OSError: If a pack cannot be written
        """
        self.published = {}
        deps = [info for info in self.base.deps.values() if info.pack_dep]
        if not deps:
            logger.info(f'No dependency to build of "{self.base.workspace.name}", skipped')
            return

        # the wheels of the whole window, then the packs: one fetch loop for
        # every dependency of the run
        wheel_files = trio.run(self._fetch, deps)

        versions = sum(len(info.versions) for info in deps)
        logger.info(
            f'Generating the dependency packs of "{self.base.workspace.name}": '
            f'{len(deps)} dependencies, {versions} versions')
        total = len(deps)
        for index, info in enumerate(deps, start=1):
            logger.info(
                f'[{index}/{total}] Building dependency packs of "{info.name}": '
                f'{len(info.versions)} versions, target={info.latest.version}')
            self._write_dep_packs(info, wheel_files)

        # commit() may clean the channel only after every pack of the run is
        # on the disk
        logger.info(f'Dependency packs of "{self.base.workspace.name}" generated')

    async def _fetch(self, deps):
        """
        Download the pure python wheel of every version of the window.

        The build encodes one tree, so it reads the pure python wheel of
        python3 only, see DOWNLOAD_MODE_PY3_ANY: a version without one is not a
        pack target and fails the run.

        Args:
            deps (list[DepBuildInfo]): The dependencies of the pack channels

        Returns:
            dict[tuple[str, str], PathStr]: {(name, version): wheel file}

        Raises:
            WheelNotFoundError: If a version has no usable wheel
            WheelHashError: If a downloaded wheel does not match its index link
            httpx2.HTTPError: If a request fails
            OSError: If a wheel cannot be written
        """
        wheel_files = {}
        targets = [(info, pin) for info in deps for pin in info.versions]
        total = len(targets)
        for index, (info, pin) in enumerate(targets, start=1):
            name = info.name
            fetcher = WheelFetcher(
                self.base.wheel_cache_of(name, pin.version), pin.source or DEFAULT_INDEX,
                name, pin.version, client=self.base.client)
            role = _role_of(info, pin)
            logger.info(
                f'[{index}/{total}] Fetching wheel of "{pin.name}=={pin.version}", '
                f'index="{fetcher.mirrors_text}", role={role}')
            try:
                try:
                    files = await fetcher.fetch_async(DOWNLOAD_MODE_PY3_ANY)
                except WheelNotFoundError as e:
                    raise WheelNotFoundError(
                        f'No usable wheel of the {role} dependency '
                        f'"{name}=={pin.version}", the dependency packs cannot be '
                        f'generated: {e}') from e
                wheel_files[(name, pin.version)] = files[0].file
                # the files of the run only: a file an earlier run left in the
                # cache folder is a leftover, the cleanup removes it
                self.base.touch(files[0].file)
                self.base.touch(fetcher.index_file)
            finally:
                await fetcher.aclose()
        return wheel_files

    def _write_dep_packs(self, info, wheel_files):
        """
        Write the packs of one dependency, see the module docstring for the layout.

        The full pack of the target version an earlier run wrote is kept as it
        is, see kept_pack: only the packs that are missing are built, so a run
        over a channel that is up to date builds nothing.

        Args:
            info (DepBuildInfo): The dependency and its versions, its latest
                pin is the only version with a full pack
            wheel_files (dict[tuple[str, str], PathStr]): The wheels fetched
                by run(), every version of the dependency is in it

        Raises:
            OSError: If a pack cannot be written
        """
        name = info.name
        target = info.latest
        dep_folder = self.base.packdep_folder.joinpath(name)

        # 1. the full pack of the target version, the only full pack of the
        # channel: a client downloads it once and updates with update packs
        # afterwards, the versions of the window do not need one
        file = dep_folder.joinpath(target.version).joinpath(FULL_PACK_FILE)
        identity = kept_pack(file, PackWheel.PACK_VERSION, target.version, '')
        self.base.touch(file)
        if identity is not None:
            logger.info(f'Full pack exists, skipped: "{file}"')
            target_pack = None
            target_checksum = identity.index_checksum
        else:
            target_pack = PackWheel(wheel_files[(name, target.version)])
            logger.info(f'Writing full pack: "{file}"')
            atomic_write_stream(file, target_pack.iter_pack_data())
            # read the identity back from the file: the same read the kept
            # path does, so the published snapshot uses the checksum of the
            # pack that is on the disk
            target_checksum = PackChecksum.from_file(file).index_checksum

        # the snapshot of the channel, read from the target full pack: the
        # repo packdep is built from this, never from a per dependency
        # latest.pack
        try:
            validate_packdep_name(name)
            validate_filename(target.version)
        except ValueError as e:
            logger.warning(
                f'The channel of "{name}=={target.version}" has no packdep-safe name or '
                f'version, the dependency is left out of packdep: {e}')
            return
        self.published[name] = (target.version, target_checksum)

        # 2. the update pack from every other version to the target. The
        # install tree of the old version is the old side of the update pack
        # (the wheel is the input of the pack build, a version of the window
        # has no full pack of its own), the pack of the target the new side,
        # shared by every update pack of the dependency; the pack of a version
        # pair that is already on the disk is kept, see kept_pack
        new_pack = target_pack
        for version, pin in info.lookbacks.items():
            file = dep_folder.joinpath(target.version).joinpath(f'update_{version}.pack')
            identity = kept_pack(file, PackWheel.PACK_VERSION, target.version, version)
            self.base.touch(file)
            if identity is not None:
                logger.info(f'Update pack exists, skipped: "{file}"')
                continue
            if new_pack is None:
                new_pack = PackWheel(wheel_files[(name, target.version)])
            old_pack = PackWheel(wheel_files[(name, version)])
            logger.info(f'Writing update pack: {version} -> {target.version}, "{file}"')
            atomic_write_stream(file, PackWheelUpdate(new_pack, old_pack).iter_pack_data())

def _role_of(info, pin):
    """
    The role of a version in the update: target or historical.

    Args:
        info (DepBuildInfo): Dependency of the version
        pin (DepInfo): Version of the dependency

    Returns:
        str: 'target' for the version of the latest commit, 'historical' for
            a version a client may still be on
    """
    return 'target' if pin is info.latest else 'historical'
